/*
ЗАДАЧА 16. РАСПРЕДЕЛИТЬ СООБЩЕНИЯ ПО КАНАЛАМ С ПРИОРИТЕТОМ

Что необходимо доработать:
  - Сейчас все сообщения отправляются в первый выходной канал.
    Нужно распределять сообщения из input по каналам outputs с учётом приоритета.
  - В первую очередь отправлять сообщение в первый канал. Если он заблокирован,
    пробовать второй, затем третий и так далее.
*/
package tasks

func Dispatch(input <-chan int, outputs []chan<- int) {
	for value := range input {
		outputs[0] <- value
	}
}
